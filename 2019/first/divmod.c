#include <stdio.h>
#include <stdlib.h>
#include <string.h>
#include <ctype.h>

#define min(a, b)	(((a) < (b)) ? (a) : (b))		/* ２個の値の最小値 */

/********************************************************************************************************************************/
/* main *************************************************************************************************************************/
/********************************************************************************************************************************/
int DEBUG = 0;										/* デバッグプリント 提出時は0 */

int main()
{

	long long		N;
	long long		i,j;
	long long		ans = 0;

	ans = 0;
	scanf("%ld", &N);
	for (i=1; i*i<N; i++) {
		if ((N%i)==0) {
			ans += N/i-1;
			if (DEBUG) printf("%ld %ld\n",ans,N/i-1);
		}
	}

	printf("%ld\n",ans);

	return 0;
}

